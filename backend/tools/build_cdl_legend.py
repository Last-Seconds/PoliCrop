"""Build data/us/cdl_legend.json from the official CropScape county statistics.

The CDL class names and display colours are taken from the USDA NASS CropScape
service (GetCDLStat), for every year in the range, for one county. Run:

    python tools/build_cdl_legend.py --fips 53075 --start 2008 --end 2025
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

import httpx

SERVICE = "https://nassgeodata.gmu.edu/axis2/services/CDLService/GetCDLStat"
ROW = re.compile(r'\{value:(\d+), count:\d+, category:"([^"]*)", color:"(#[0-9A-Fa-f]{6})"')


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--fips", default="53075")
    ap.add_argument("--start", type=int, default=2008)
    ap.add_argument("--end", type=int, default=2025)
    ap.add_argument("--out", default=str(Path(__file__).resolve().parents[2] / "data/us/cdl_legend.json"))
    args = ap.parse_args()

    classes: dict[int, dict] = {}
    with httpx.Client(timeout=120) as client:
        for year in range(args.start, args.end + 1):
            text = None
            for attempt in range(4):
                try:
                    resp = client.get(SERVICE, params={"year": year, "fips": args.fips, "format": "json"})
                    m = re.search(r"<returnURL>([^<]+)</returnURL>", resp.text)
                    if not m:
                        print(f"{year}: no stats ({resp.text[:120]!r})")
                        break
                    text = client.get(m.group(1)).text
                    break
                except httpx.HTTPError as exc:
                    print(f"{year}: attempt {attempt + 1} failed: {exc!r}")
            if text is None:
                continue
            n = 0
            for code, name, color in ROW.findall(text):
                entry = classes.setdefault(int(code), {"name": name, "color": color.upper(), "years": []})
                entry["years"].append(year)
                n += 1
            print(f"{year}: {n} classes")

    out = {
        "_source": f"USDA NASS CropScape GetCDLStat, county FIPS {args.fips}, years {args.start}-{args.end}",
        "_note": "Generated by backend/tools/build_cdl_legend.py. 'years' lists the years the class occurs in this county.",
        "classes": {str(k): classes[k] for k in sorted(classes)},
    }
    Path(args.out).write_text(json.dumps(out, indent=1) + "\n")
    print(f"wrote {len(classes)} classes to {args.out}")


if __name__ == "__main__":
    main()
